/* global console, URL */
// Bundle supabase/templates/*.html into the auth-mailer edge function so the
// HTML files stay the single source of truth.
import { readFileSync, writeFileSync } from 'node:fs';

const files = {
  'confirm-signup': 'confirm-signup.html',
  'reset-password': 'reset-password.html',
  'change-email': 'change-email.html',
  reauthentication: 'reauthentication.html',
  invite: 'invite.html',
  'magic-link': 'magic-link.html',
};
const dir = new URL('../supabase/templates/', import.meta.url);
const entries = Object.entries(files)
  .map(
    ([key, file]) =>
      `  ${JSON.stringify(key)}: ${JSON.stringify(readFileSync(new URL(file, dir), 'utf8'))},`,
  )
  .join('\n');
writeFileSync(
  new URL('../supabase/functions/auth-mailer/templates.ts', import.meta.url),
  `// Generated by scripts/build-mailer-templates.mjs from supabase/templates. Do not edit.\nexport const templates = {\n${entries}\n} as const;\n`,
);
console.log('Wrote supabase/functions/auth-mailer/templates.ts');
